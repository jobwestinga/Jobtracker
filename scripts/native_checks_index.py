"""Keep the native check runner's registration list in step with its suites.

Swift has no runtime method discovery without the testing macros, which the
Command Line Tools do not ship, so `JobTrackerChecks/main.swift` lists every
`func name()` of every `struct X: CheckSuite`. `--check` reports drift.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHECKS = Path("native/macos/Sources/JobTrackerChecks")


def render(root: Path = ROOT) -> str:
    entries = []
    for path in sorted((root / CHECKS).glob("*Checks.swift")):
        suite = None
        for line in path.read_text().splitlines():
            match = re.match(r"struct (\w+): CheckSuite \{", line)
            if match:
                suite = match.group(1)
                continue
            match = re.match(r"    func (\w+)\(\)( throws)?", line)
            if match and suite:
                entries.append((suite, match.group(1)))
    lines = [
        "// Generated by scripts/native_checks_index.py. Macro-free check runner: the",
        "// Command Line Tools ship no Testing/XCTest macro plugins, so native checks",
        "// run as `swift run JobTrackerChecks [filter]`.",
        "import Foundation",
        "",
        "let checks: [(String, () throws -> Void)] = [",
        *(f'    ("{suite}.{name}", {{ try {suite}().{name}() }}),' for suite, name in entries),
        "]",
        "",
        "exit(runChecks(checks))",
        "",
    ]
    return "\n".join(lines)


def check(root: Path = ROOT, *, write: bool = False) -> list[str]:
    target = root / CHECKS / "main.swift"
    expected = render(root)
    if write:
        if not target.exists() or target.read_text() != expected:
            target.write_text(expected)
        return []
    if not target.exists() or target.read_text() != expected:
        return [f"{CHECKS}/main.swift is stale; run python3 scripts/native_checks_index.py"]
    return []


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    errors = check(write=not args.check)
    print("\n".join(errors) if errors else "Native check index is current.")
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
