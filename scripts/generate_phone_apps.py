"""Generate two static entry shells from the complete shared browser shell.

There is no runtime build. Commit generated assets; dev.py check detects drift.
Metadata and routes live in web/shared/profile.js, not in parallel templates.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated(root: Path) -> dict[Path, str]:
    web = root / "web"
    source = (web / "shared/profile.js").read_text()
    profiles = json.loads(re.search(r"export const PROFILES = (\{[\s\S]*?\n\});", source).group(1))
    template = (web / "index.html").read_text()
    result = {}
    for key in ("weight", "jobtracker"):
        profile = profiles[key]
        shell = template.replace('<script src="/legacy.js"></script>\n', '')
        shell = shell.replace('<html lang="en">', f'<html lang="en" data-profile="{key}">')
        shell = shell.replace('<head>', '<head>\n<!-- Generated by scripts/generate_phone_apps.py; edit web/index.html. -->')
        shell = re.sub(r'<title>.*?</title>', f'<title>{profile["name"]}</title>', shell)
        shell = re.sub(r'(<meta name="apple-mobile-web-app-title" content=")[^"]+', rf'\g<1>{profile["name"]}', shell)
        shell = shell.replace('href="/manifest.webmanifest"', f'href="{profile["manifest"]}"')
        shell = re.sub(r'(<link rel="apple-touch-icon"[^>]*href=")[^"]+', rf'\g<1>{profile["icon"]}-touch.png', shell)
        shell = shell.replace('<h1>JobTracker</h1>', f'<h1>{profile["name"]}</h1>')
        title = "Weight" if key == "weight" else "Subjects"
        shell = shell.replace('<h1 id="view-title">Weight</h1>', f'<h1 id="view-title">{title}</h1>')
        # Keep shared feature mount nodes; navigation itself only exposes this app.
        shell = re.sub(r'    <button class="tab[^\n]*data-view="([^"]+)"[^\n]*\n',
                       lambda match: match[0] if match[1] in profile["views"] else '', shell)
        if key == "weight":
            shell = shell.replace('class="tabbar five"', 'class="tabbar hidden"')
        else:
            shell = shell.replace('class="tabbar five"', 'class="tabbar four"')
            shell = shell.replace('id="view-today" class="view hidden"', 'id="view-today" class="view"')
            shell = shell.replace('id="view-weight" class="view"', 'id="view-weight" class="view hidden"')
        result[web / profile["path"].strip("/") / "index.html"] = shell
        manifest = {
            "id": profile["identity"], "name": profile["name"], "short_name": profile["name"],
            "start_url": profile["path"], "scope": profile["scope"], "display": "standalone",
            "background_color": "#0B1220", "theme_color": "#0B1220", "orientation": "any",
            "icons": [{"src": profile["icon"] + ".png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"}],
        }
        result[web / profile["manifest"].lstrip("/")] = json.dumps(manifest, indent=2) + "\n"
        if key == "weight":
            # Weight owns the root identity: adding / to the Home Screen installs Weight.
            result[web / "manifest.webmanifest"] = json.dumps(manifest, indent=2) + "\n"
    return result


def check(root: Path, *, write: bool = False) -> list[str]:
    errors = []
    for path, content in generated(root).items():
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        elif not path.is_file() or path.read_text() != content:
            errors.append(f"{path.relative_to(root)}: stale phone shell/metadata; run python3 scripts/generate_phone_apps.py --write")
    return errors


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    errors = check(ROOT, write=args.write)
    print("\n".join(errors) if errors else "Phone entry shells and metadata agree.")
    raise SystemExit(bool(errors))
