"""Generate frontend design tokens from the theme authority and UI roles.

``jobtracker/core/themes.py`` stays the only palette/FX definition and
``design/ui_roles.json`` holds the F1 semantic roles. This script loads
``themes.py`` as a standalone module (no package import, no database
singleton), resolves every palette/FX pair with ``get_tokens`` and writes a
checked, generated Swift source for the native app. ``--check`` reports drift.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEMES = Path("jobtracker/core/themes.py")
ROLES = Path("design/ui_roles.json")
SWIFT_OUT = Path("native/macos/Sources/JobTrackerKit/Theme/TokensData.generated.swift")

_COLOR_KEYS = ("BG_PRIMARY", "BG_SECONDARY", "BG_TERTIARY", "BORDER_COLOR", "BORDER_FOCUS",
               "TEXT_PRIMARY", "TEXT_SECONDARY", "TEXT_DIMMED", "ACCENT", "ACCENT_GREEN", "ACCENT_RED")
_REFERENCE = re.compile(r"^(?:(?P<width>\d+(?:\.\d+)?)px solid )?\{(?P<token>[A-Z_]+?)(?:_A(?P<alpha>\d+))?\}$")


def _load_themes(root: Path):
    spec = importlib.util.spec_from_file_location("_jobtracker_theme_authority", root / THEMES)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _reference(value: str) -> dict:
    match = _REFERENCE.match(value.strip())
    if not match:
        raise ValueError(f"Unsupported FX token value {value!r}")
    out = {"token": match["token"], "alpha": int(match["alpha"]) if match["alpha"] else 255}
    if match["width"]:
        out["width"] = float(match["width"])
    return out


def build(root: Path = ROOT) -> dict:
    themes = _load_themes(root)
    roles = json.loads((root / ROLES).read_text())
    fx = {}
    for name, style in themes.FX_STYLES.items():
        fx[name] = {
            "card_background": _reference(style["CARD_BG"]),
            "card_hover_background": _reference(style["CARD_HOVER_BG"]),
            "card_border": _reference(style["CARD_BORDER_STYLE"]),
            "card_hover_border": _reference(style["CARD_HOVER_BORDER"]),
            "timer_background": _reference(style["TIMER_BG"]),
            "timer_border": _reference(style["TIMER_BORDER"]),
            "radius": float(style["RADIUS"].rstrip("px")),
            "subject_radius": float(style["SUBJECT_RADIUS"].rstrip("px")),
            "task_radius": float(style["TASK_RADIUS"].rstrip("px")),
        }
    palettes = {name: {key: values[key] for key in _COLOR_KEYS} for name, values in themes.PALETTES.items()}
    # Every resolved pair must agree with get_tokens, the Qt stylesheet source.
    for palette in palettes:
        for style in fx:
            tokens = themes.get_tokens(style, palette)
            assert all(tokens[key] == palettes[palette][key] for key in _COLOR_KEYS)
    return {
        "palettes": palettes,
        "palette_order": list(themes.PALETTES),
        "fx": fx,
        "fx_order": list(themes.FX_STYLES),
        "themes": [
            {"name": name, "fx": pair[0], "palette": pair[1], "description": themes.THEME_DESCRIPTIONS.get(name, "")}
            for name, pair in themes.THEME_PRESETS.items()
        ],
        "roles": roles,
    }


def render_swift(data: dict) -> str:
    payload = json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False)
    if '"""#' in payload:
        raise ValueError("token payload cannot contain a raw-string terminator")
    return (
        "// Generated by scripts/generate_ui_tokens.py from jobtracker/core/themes.py\n"
        "// and design/ui_roles.json. Do not edit; regenerate instead.\n\n"
        "enum TokensData {\n"
        "    static let json = #\"\"\"\n"
        f"{payload}\n"
        "\"\"\"#\n"
        "}\n"
    )


def check(root: Path = ROOT, *, write: bool = False) -> list[str]:
    expected = render_swift(build(root))
    target = root / SWIFT_OUT
    if write:
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text() != expected:
            target.write_text(expected)
        return []
    if not target.exists() or target.read_text() != expected:
        return [f"{SWIFT_OUT} is stale; run python3 scripts/generate_ui_tokens.py"]
    return []


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing.")
    args = parser.parse_args(argv)
    errors = check(ROOT, write=not args.check)
    print("\n".join(errors) if errors else "UI tokens are current.")
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
